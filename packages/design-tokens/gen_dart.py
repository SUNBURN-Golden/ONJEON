#!/usr/bin/env python3
"""Generate apps/mobile/lib/design/tokens.g.dart from packages/design-tokens/tokens.json.

  python3 -I packages/design-tokens/gen_dart.py            # write the file
  python3 -I packages/design-tokens/gen_dart.py --check    # exit 1 when the file is stale

The generated file is committed; --check is what keeps it from drifting from tokens.json.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / "tokens.json"
OUT = ROOT / "apps" / "mobile" / "lib" / "design" / "tokens.g.dart"
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def camel(name):
    head, *rest = re.split(r"[-_]", name)
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def num(v):
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise ValueError(f"not a number: {v!r}")
    return f"{float(v)}"


def render(tokens):
    colors, weights, texts = tokens["color"], tokens["weight"], tokens["text"]
    for k, v in colors.items():
        if not HEX.match(v):
            raise ValueError(f"color {k}: {v!r} is not #RRGGBB")
    for k, t in texts.items():
        if t["weight"] not in weights:
            raise ValueError(f"text {k}: unknown weight {t['weight']!r}")
        if t["color"] not in colors:
            raise ValueError(f"text {k}: unknown colour {t['color']!r}")
    out = [
        "// @generated by packages/design-tokens/gen_dart.py from packages/design-tokens/tokens.json.",
        "// Do not edit; run `python3 -I packages/design-tokens/gen_dart.py`.",
        "",
        "import 'package:flutter/painting.dart';",
        "",
        "/// Design tokens measured from the selected reference screen (design spec section 3).",
        "abstract final class OnjeonColors {",
    ]
    for k, v in colors.items():
        out.append(f"  static const Color {camel(k)} = Color(0xFF{v[1:].upper()});")
    out += ["}", "", "abstract final class OnjeonSpace {"]
    for k, v in tokens["space"].items():
        out.append(f"  static const double {camel(k)} = {num(v)};")
    out += ["}", "", "abstract final class OnjeonDimension {"]
    for k, v in tokens["dimension"].items():
        out.append(f"  static const double {camel(k)} = {num(v)};")
    out += ["}", "", "abstract final class OnjeonText {"]
    for k, t in texts.items():
        out += [
            f"  static const TextStyle {camel(k)} = TextStyle(",
            f"    fontSize: {num(t['size'])},",
            f"    fontWeight: FontWeight.w{weights[t['weight']]},",
            f"    color: OnjeonColors.{camel(t['color'])},",
            "  );",
        ]
    out += ["}", ""]
    return "\n".join(out)


def main(argv):
    tokens = json.loads(SRC.read_text(encoding="utf-8"))
    text = render(tokens)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT.relative_to(ROOT)}; run gen_dart.py", file=sys.stderr)
            return 1
        print("tokens.g.dart is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
