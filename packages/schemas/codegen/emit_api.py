"""API emitters: Rust server types (crate onjeon-api-types), TypeScript and Dart clients.

Input is the ApiModel (openapi_model.py). Contract structs and vocabulary enums are not repeated: the
API code imports them from the contracts packages (onjeon_contracts / ../ts / ../dart).

Skeleton operations (x-onjeon-skeleton: true) and the structs only they use are written to separate
places that the default surface does not export:
  Rust        `#[cfg(feature = "skeleton")]` (feature off by default)
  TypeScript  skeleton.ts, not exported from index.ts
  Dart        lib/skeleton.dart, not exported from lib/onjeon_api.dart
"""
from __future__ import annotations

import json

import emit_dart
import emit_rust
import emit_ts
from openapi_model import ApiModel, Operation
from schema_model import Type, camel, pascal

SRC = "packages/schemas/openapi/*.v1.yaml"
HEADER_RS = f"""// @generated by packages/schemas/codegen/gen.py from {SRC}
// (contract types come from onjeon-contracts). Do not edit; run `bash packages/schemas/codegen/gen.sh`.
"""
HEADER_TS = f"""// @generated by packages/schemas/codegen/gen.py from {SRC}
// (contract types come from ../ts). Do not edit; run `bash packages/schemas/codegen/gen.sh`.
"""
HEADER_DART = f"""// @generated by packages/schemas/codegen/gen.py from {SRC}
// (contract types come from package:onjeon_contracts). Do not edit; run `bash packages/schemas/codegen/gen.sh`.
"""
CACHE_VARIANT = {"public_keyed": "PublicKeyed", "no_store": "NoStore", "private_no_store": "PrivateNoStore"}


def lit(text: str) -> str:
    if "$" in text:
        raise ValueError(f"'$' in a generated string literal: {text!r}")
    return json.dumps(text, ensure_ascii=False)


def refs_and_enums(structs) -> tuple:
    refs, enums = set(), set()

    def walk(t: Type):
        if t.kind == "ref":
            refs.add(t.name)
        if t.kind == "enum":
            enums.add(pascal(t.name))
        if t.item is not None:
            walk(t.item)

    for st in structs:
        for f in st.fields:
            walk(f.type)
    return refs, enums


def split(am: ApiModel):
    live = [s for s in am.api_structs if s.name not in am.skeleton_only]
    skel = [s for s in am.api_structs if s.name in am.skeleton_only]
    return live, skel


def ops_split(am: ApiModel):
    return [o for o in am.ops if not o.skeleton], [o for o in am.ops if o.skeleton]


# ---------------------------------------------------------------- Rust
def rust_op(o: Operation) -> str:
    opt = lambda v: f"Some({lit(v)})" if v else "None"
    keys = ", ".join(lit(k) for k in o.cache_key)
    roles = ", ".join(lit(k) for k in o.roles)
    params = ", ".join(lit(k) for k in o.path_params)
    return (
        "    Operation {\n"
        f"        id: {lit(o.id)},\n"
        f"        surface: Surface::{pascal(o.surface)},\n"
        f"        method: {lit(o.method)},\n"
        f"        path: {lit(o.path)},\n"
        f"        cache: CacheClass::{CACHE_VARIANT[o.cache]},\n"
        f"        cache_key: &[{keys}],\n"
        f"        roles: &[{roles}],\n"
        f"        path_params: &[{params}],\n"
        f"        request: {opt(o.request)},\n"
        f"        response: {lit(o.response)},\n"
        f"        query: {opt(o.query)},\n"
        f"        multipart: {str(o.multipart).lower()},\n"
        f"        skeleton: {str(o.skeleton).lower()},\n"
        f"        flag: {opt(o.flag)},\n"
        f"        summary: {lit(o.summary)},\n"
        "    },\n"
    )


def rust_operations(am: ApiModel) -> str:
    live, skel = ops_split(am)
    out = [HEADER_RS, f'''
/// `info.version` of the OpenAPI documents these tables were generated from.
pub const API_VERSION: &str = {lit(am.docs["public"]["info"]["version"])};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Surface {{
    Public,
    Personal,
    Console,
}}

/// Cache class of the success response. `PublicKeyed` is the only class a shared cache may store.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum CacheClass {{
    /// `Cache-Control: public, ...`; the cache key contains `cache_key` (always release_id).
    PublicKeyed,
    /// `Cache-Control: no-store`.
    NoStore,
    /// `Cache-Control: private, no-store`. Personal and console responses, always.
    PrivateNoStore,
}}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Operation {{
    pub id: &'static str,
    pub surface: Surface,
    pub method: &'static str,
    pub path: &'static str,
    pub cache: CacheClass,
    pub cache_key: &'static [&'static str],
    pub roles: &'static [&'static str],
    pub path_params: &'static [&'static str],
    /// Struct name of the request body (the form fields for multipart).
    pub request: Option<&'static str>,
    /// Struct name of the 200 body. It always has `release_id`.
    pub response: &'static str,
    pub query: Option<&'static str>,
    pub multipart: bool,
    pub skeleton: bool,
    /// Feature flag of a skeleton operation (default off).
    pub flag: Option<&'static str>,
    pub summary: &'static str,
}}

/// Operations of the default surface. Skeleton operations are not in this list.
pub const OPERATIONS: &[Operation] = &[
''']
    out += [rust_op(o) for o in live]
    out.append("];\n")
    out.append('''
/// Reserved skeleton operations (제3부 §58). Compiled only with the `skeleton` feature; their flags are off by default.
#[cfg(feature = "skeleton")]
pub const SKELETON_OPERATIONS: &[Operation] = &[
''')
    out += [rust_op(o) for o in skel]
    out.append("];\n")
    return "".join(out)


def rust_types(am: ApiModel) -> str:
    cfg = {n: '#[cfg(feature = "skeleton")]' for n in am.skeleton_only}
    return emit_rust.emit_types(
        am.model, structs=am.api_structs, header=HEADER_RS,
        preamble="use onjeon_contracts::*;\nuse serde::{Deserialize, Serialize};\n\n", cfg=cfg)


def rust_mod() -> str:
    return HEADER_RS + "#![allow(clippy::all)]\n\npub mod operations;\npub mod types;\n"


# ---------------------------------------------------------------- TypeScript
def ts_imports(structs, api_names_in_other_file: set | None = None) -> str:
    refs, enums = refs_and_enums(structs)
    own = {s.name for s in structs}
    other = {r for r in refs if r in (api_names_in_other_file or set())}
    contract = sorted((refs - own - other) | enums)
    out = ""
    if contract:
        out += "\nimport type {\n" + "".join(f"  {n},\n" for n in contract) + '} from "../ts/index";\n'
    if other:
        out += "import type {\n" + "".join(f"  {n},\n" for n in sorted(other)) + '} from "./types";\n'
    return out or "\n"


def ts_op(o: Operation) -> str:
    def opt(v):
        return lit(v) if v else "null"
    return (
        "  {\n"
        f"    id: {lit(o.id)},\n"
        f"    surface: {lit(o.surface)},\n"
        f"    method: {lit(o.method)},\n"
        f"    path: {lit(o.path)},\n"
        f"    cache: {lit(o.cache)},\n"
        f"    cacheKey: [{', '.join(lit(k) for k in o.cache_key)}],\n"
        f"    roles: [{', '.join(lit(k) for k in o.roles)}],\n"
        f"    pathParams: [{', '.join(lit(k) for k in o.path_params)}],\n"
        f"    request: {opt(o.request)},\n"
        f"    response: {lit(o.response)},\n"
        f"    query: {opt(o.query)},\n"
        f"    multipart: {str(o.multipart).lower()},\n"
        f"    skeleton: {str(o.skeleton).lower()},\n"
        f"    flag: {opt(o.flag)},\n"
        f"    summary: {lit(o.summary)},\n"
        "  },\n"
    )


TS_OPERATION_TYPES = '''
export type Surface = "public" | "personal" | "console";
/** public_keyed is the only class a shared cache may store; the cache key contains cacheKey (release_id). */
export type CacheClass = "public_keyed" | "no_store" | "private_no_store";

export interface Operation {
  id: string;
  surface: Surface;
  method: string;
  path: string;
  cache: CacheClass;
  cacheKey: string[];
  roles: string[];
  pathParams: string[];
  /** Struct name of the request body (the form fields for multipart). */
  request: string | null;
  /** Struct name of the 200 body. It always has release_id. */
  response: string;
  query: string | null;
  multipart: boolean;
  skeleton: boolean;
  /** Feature flag of a skeleton operation (default off). */
  flag: string | null;
  summary: string;
}
'''


def ts_files(am: ApiModel) -> dict:
    live, skel = split(am)
    lops, sops = ops_split(am)
    live_names = {s.name for s in live}
    ops = HEADER_TS + TS_OPERATION_TYPES + "\n/** Operations of the default surface. Skeleton operations are in skeleton.ts. */\n"
    ops += f"export const API_VERSION = {lit(am.docs['public']['info']['version'])};\n"
    ops += "export const operations: readonly Operation[] = [\n" + "".join(ts_op(o) for o in lops) + "];\n"
    skel_ts = (HEADER_TS + '\nimport type { Operation } from "./operations";\n' + ts_imports(skel, live_names)
               + "\n/** Reserved skeleton operations (제3부 §58). Not exported from index.ts; every flag is off by default. */\n"
               + "export const skeletonOperations: readonly Operation[] = [\n" + "".join(ts_op(o) for o in sops) + "];\n"
               + emit_ts.emit_types(am.model, structs=skel, imports="", header="").rstrip() + "\n")
    cfg = {
        "compilerOptions": {"target": "ES2020", "module": "ES2020", "moduleResolution": "Bundler", "strict": True,
                            "noUnusedLocals": True, "noEmit": True, "skipLibCheck": False, "types": []},
        "files": ["index.ts", "types.ts", "operations.ts", "skeleton.ts"],
    }
    pkg = {"name": "onjeon-api", "version": am.docs["public"]["info"]["version"], "private": True,
           "description": "Generated ONJEON API types (default surface; skeleton.ts is opt-in)", "types": "index.ts"}
    return {
        "types.ts": emit_ts.emit_types(am.model, structs=live, imports=ts_imports(live), header=HEADER_TS),
        "operations.ts": ops,
        "skeleton.ts": skel_ts,
        "index.ts": HEADER_TS + 'export * from "./types";\nexport * from "./operations";\n',
        "tsconfig.json": json.dumps(cfg, indent=2) + "\n",
        "package.json": json.dumps(pkg, indent=2) + "\n",
    }


# ---------------------------------------------------------------- Dart
def dart_op(o: Operation) -> str:
    def opt(v):
        return lit(v) if v else "null"
    return (
        "  Operation(\n"
        f"    id: {lit(o.id)},\n"
        f"    surface: Surface.{camel(o.surface)},\n"
        f"    method: {lit(o.method)},\n"
        f"    path: {lit(o.path)},\n"
        f"    cache: CacheClass.{camel(CACHE_VARIANT[o.cache])},\n"
        f"    cacheKey: [{', '.join(lit(k) for k in o.cache_key)}],\n"
        f"    roles: [{', '.join(lit(k) for k in o.roles)}],\n"
        f"    pathParams: [{', '.join(lit(k) for k in o.path_params)}],\n"
        f"    request: {opt(o.request)},\n"
        f"    response: {lit(o.response)},\n"
        f"    query: {opt(o.query)},\n"
        f"    multipart: {str(o.multipart).lower()},\n"
        f"    skeleton: {str(o.skeleton).lower()},\n"
        f"    flag: {opt(o.flag)},\n"
        f"    summary: {lit(o.summary)},\n"
        "  ),\n"
    )


DART_OPERATION_TYPES = '''
enum Surface { public, personal, console }

/// publicKeyed is the only class a shared cache may store; the cache key contains cacheKey (release_id).
enum CacheClass { publicKeyed, noStore, privateNoStore }

class Operation {
  final String id;
  final Surface surface;
  final String method;
  final String path;
  final CacheClass cache;
  final List<String> cacheKey;
  final List<String> roles;
  final List<String> pathParams;

  /// Struct name of the request body (the form fields for multipart).
  final String? request;

  /// Struct name of the 200 body. It always has release_id.
  final String response;
  final String? query;
  final bool multipart;
  final bool skeleton;

  /// Feature flag of a skeleton operation (default off).
  final String? flag;
  final String summary;

  const Operation({
    required this.id,
    required this.surface,
    required this.method,
    required this.path,
    required this.cache,
    required this.cacheKey,
    required this.roles,
    required this.pathParams,
    required this.request,
    required this.response,
    required this.query,
    required this.multipart,
    required this.skeleton,
    required this.flag,
    required this.summary,
  });
}
'''


def dart_files(am: ApiModel, version: str) -> dict:
    live, skel = split(am)
    lops, sops = ops_split(am)
    contracts = "\nimport 'package:onjeon_contracts/onjeon_contracts.dart';\n"
    ops = HEADER_DART + DART_OPERATION_TYPES + "\n/// `info.version` of the OpenAPI documents.\n"
    ops += f"const String apiVersion = {lit(am.docs['public']['info']['version'])};\n"
    ops += "\n/// Operations of the default surface. Skeleton operations are in skeleton.dart.\n"
    ops += "const List<Operation> operations = [\n" + "".join(dart_op(o) for o in lops) + "];\n"
    refs, enums = refs_and_enums(skel)
    needs_contracts = bool((refs - {s.name for s in skel}) | enums)  # an unused import is an analyzer warning
    skel_types = emit_dart.emit_types(
        am.model, structs=skel, imports=(contracts if needs_contracts else "\n") + "import 'operations.dart';\n", header=HEADER_DART)
    skel_dart = (skel_types.rstrip() + "\n\n/// Reserved skeleton operations (제3부 §58). Not exported from onjeon_api.dart; every flag is off by default.\n"
                 + "const List<Operation> skeletonOperations = [\n" + "".join(dart_op(o) for o in sops) + "];\n")
    pubspec = (
        "name: onjeon_api\n"
        "description: Generated ONJEON API types (default surface; skeleton.dart is opt-in; do not edit)\n"
        f"version: {am.docs['public']['info']['version']}\n"
        "publish_to: none\n"
        "environment:\n  sdk: '>=3.0.0 <4.0.0'\n"
        "dependencies:\n  onjeon_contracts:\n    path: ../dart\n"
    )
    return {
        "pubspec.yaml": pubspec,
        "analysis_options.yaml": emit_dart.emit_analysis_options(),
        "lib/onjeon_api.dart": HEADER_DART + "\nlibrary onjeon_api;\n\nexport 'src/operations.dart';\nexport 'src/types.dart';\n",
        "lib/skeleton.dart": HEADER_DART + "\nlibrary skeleton;\n\nexport 'src/skeleton.dart';\n",
        "lib/src/types.dart": emit_dart.emit_types(am.model, structs=live, imports=contracts, header=HEADER_DART),
        "lib/src/operations.dart": ops,
        "lib/src/skeleton.dart": skel_dart,
    }


def emit(am: ApiModel, version: str) -> dict:
    """{'rust': {...}, 'ts': {...}, 'dart': {...}} relative file name -> text."""
    return {
        "rust": {"mod.rs": rust_mod(), "types.rs": rust_types(am), "operations.rs": rust_operations(am)},
        "ts": ts_files(am),
        "dart": dart_files(am, version),
    }
