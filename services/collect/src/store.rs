//! Object stores behind one write-once interface (port of `source_archive.py`'s stores).
//!
//! `put_new` creates a key only if absent; callers go through `archive::put_once`, which
//! resolves a pre-existing key by comparing bytes. Nothing in this interface can delete or
//! overwrite an object.

use std::io::Write;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

static NEXT_TEMP: AtomicU64 = AtomicU64::new(0);

use crate::digest::sha256_hex;
pub use crate::s3::S3Store;

/// The key already exists (the conditional create lost the race or the object is present).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Exists(pub String);

impl std::fmt::Display for Exists {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "key exists: {}", self.0)
    }
}

impl std::error::Error for Exists {}

/// Result of `stored_sha256`: absent, a recorded digest, or present without one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StoredSha {
    Absent,
    Sha(String),
    /// The key exists but has no recorded checksum — callers must download to compare.
    NoChecksum,
}

/// Write-once object storage. Implementors never overwrite or delete.
pub trait Store {
    /// Create `key` with `body`; fails with [`Exists`] if the key is already there.
    fn put_new(&self, key: &str, body: &[u8], content_type: &str) -> Result<(), StoreError>;
    fn get(&self, key: &str) -> Result<Vec<u8>, StoreError>;
    /// The SHA-256 recorded for `key` at upload time, if the backend stores one.
    fn stored_sha256(&self, key: &str) -> Result<StoredSha, StoreError>;
    fn exists(&self, key: &str) -> Result<bool, StoreError>;
    /// All keys under `prefix`, sorted. `""` lists the whole store.
    fn list(&self, prefix: &str) -> Result<Vec<String>, StoreError>;
    /// Store label for reports: never an endpoint URL (it can carry an account id).
    fn describe(&self) -> String;
}

/// A store failure. For remote backends the message is the error *kind* only: upstream
/// messages can carry the endpoint URL (an R2 account id), so they are withheld the same
/// way `with_budget` does in Python.
#[derive(Debug)]
pub struct StoreError {
    pub kind: &'static str,
    pub message: String,
}

impl StoreError {
    pub fn io(op: &'static str, e: &std::io::Error) -> Self {
        Self {
            kind: op,
            message: format!("{op}: {}", e.kind()),
        }
    }
    /// A storage error that must not echo upstream detail (endpoint, account id, secrets).
    pub fn remote(kind: &'static str) -> Self {
        Self {
            kind,
            message: kind.into(),
        }
    }
}

impl std::fmt::Display for StoreError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "storage error: {}", self.message)
    }
}

impl std::error::Error for StoreError {}

impl From<Exists> for StoreError {
    fn from(e: Exists) -> Self {
        Self {
            kind: "exists",
            message: e.to_string(),
        }
    }
}

/// `file:///dir` store: one file per key under `root`, create-if-absent by an atomic link.
pub struct LocalStore {
    pub root: PathBuf,
}

impl LocalStore {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    fn path(&self, key: &str) -> Result<PathBuf, StoreError> {
        // Keys are generated by this crate, but a key reaching here from a caller must not
        // be able to step outside the store root.
        if key
            .split('/')
            .any(|p| p.is_empty() || p == "." || p == "..")
        {
            return Err(StoreError {
                kind: "bad_key",
                message: format!("unsafe key {key:?}"),
            });
        }
        let mut path = self.root.clone();
        for component in key.split('/') {
            path.push(component);
            match std::fs::symlink_metadata(&path) {
                Ok(meta) if meta.file_type().is_symlink() => {
                    return Err(StoreError::remote("symlink_refused"))
                }
                Ok(_) => (),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => (),
                Err(e) => return Err(StoreError::io("metadata", &e)),
            }
        }
        Ok(path)
    }
}

impl Store for LocalStore {
    fn put_new(&self, key: &str, body: &[u8], _content_type: &str) -> Result<(), StoreError> {
        let p = self.path(key)?;
        if p.exists() {
            return Err(Exists(key.into()).into());
        }
        if let Some(d) = p.parent() {
            std::fs::create_dir_all(d).map_err(|e| StoreError::io("mkdir", &e))?;
        }
        // Atomic create-if-absent: a concurrent writer gets Exists, never an overwrite.
        let tmp = p.with_file_name(format!(
            "{}.{}.{}.partial",
            p.file_name().unwrap_or_default().to_string_lossy(),
            std::process::id(),
            NEXT_TEMP.fetch_add(1, Ordering::Relaxed)
        ));
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&tmp)
            .map_err(|e| StoreError::io("create_temp", &e))?;
        if let Err(e) = file.write_all(body).and_then(|_| file.sync_all()) {
            let _ = std::fs::remove_file(&tmp);
            return Err(StoreError::io("write", &e));
        }
        let res = std::fs::hard_link(&tmp, &p);
        let _ = std::fs::remove_file(&tmp);
        match res {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                Err(Exists(key.into()).into())
            }
            Err(e) => Err(StoreError::io("link", &e)),
        }
    }

    fn get(&self, key: &str) -> Result<Vec<u8>, StoreError> {
        std::fs::read(self.path(key)?).map_err(|e| StoreError::io("read", &e))
    }

    fn stored_sha256(&self, key: &str) -> Result<StoredSha, StoreError> {
        // A local file has no stored checksum; existence is the only information HEAD gives.
        Ok(if self.exists(key)? {
            StoredSha::NoChecksum
        } else {
            StoredSha::Absent
        })
    }

    fn exists(&self, key: &str) -> Result<bool, StoreError> {
        Ok(self.path(key)?.is_file())
    }

    fn list(&self, prefix: &str) -> Result<Vec<String>, StoreError> {
        let base = if prefix.is_empty() {
            self.root.clone()
        } else {
            self.path(prefix)?
        };
        let mut out = Vec::new();
        if base.is_dir() {
            let mut stack = vec![base];
            while let Some(d) = stack.pop() {
                for e in std::fs::read_dir(&d).map_err(|e| StoreError::io("list", &e))? {
                    let p = e.map_err(|e| StoreError::io("list", &e))?.path();
                    if std::fs::symlink_metadata(&p)
                        .map_err(|e| StoreError::io("metadata", &e))?
                        .file_type()
                        .is_symlink()
                    {
                        return Err(StoreError::remote("symlink_refused"));
                    }
                    if p.is_dir() {
                        stack.push(p);
                    } else if p.is_file()
                        && !p
                            .file_name()
                            .map(|n| n.to_string_lossy().ends_with(".partial"))
                            .unwrap_or(true)
                    {
                        out.push(p);
                    }
                }
            }
        }
        out.sort();
        Ok(out
            .iter()
            .map(|p| {
                p.strip_prefix(&self.root)
                    .unwrap_or(p)
                    .to_string_lossy()
                    .replace('\\', "/")
            })
            .collect())
    }

    fn describe(&self) -> String {
        "file".into()
    }
}

/// Parse `file:///dir` or `s3://bucket[/prefix]`; S3 endpoints need credentials and obey the
/// provider gate (`s3::open`). This is the library entry the CLI uses.
pub fn local(target: &str) -> Result<LocalStore, StoreError> {
    target
        .strip_prefix("file://")
        .map(LocalStore::new)
        .ok_or_else(|| StoreError {
            kind: "bad_target",
            message: format!("target must be file:///dir, got {target}"),
        })
}

pub use crate::s3::{open, Credentials, Provider};

/// The digest of every key under `prefix` — used by `verify_copy` to pin a store.
pub fn listing_of(
    st: &dyn Store,
) -> Result<std::collections::BTreeMap<String, String>, StoreError> {
    let mut out = std::collections::BTreeMap::new();
    for key in st.list("")? {
        out.insert(key.clone(), sha256_hex(&st.get(&key)?));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn archive_local_put_new_is_atomic() {
        let dir = std::env::temp_dir().join(format!("oc-store-{}", std::process::id()));
        let st = LocalStore::new(&dir);
        st.put_new("a/b/k", b"x", "text/plain").unwrap();
        assert!(matches!(
            st.put_new("a/b/k", b"y", "text/plain"),
            Err(e) if e.kind == "exists"
        ));
        assert_eq!(st.get("a/b/k").unwrap(), b"x");
        assert_eq!(st.list("").unwrap(), vec!["a/b/k".to_string()]);
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn archive_local_rejects_traversal_keys() {
        let dir = std::env::temp_dir().join(format!("oc-store-t-{}", std::process::id()));
        let st = LocalStore::new(&dir);
        for bad in ["../x", "a/../x", "/etc/x", "", "a//b", "a/./b"] {
            assert!(st.put_new(bad, b"x", "t/t").is_err(), "{bad}");
        }
        std::fs::remove_dir_all(&dir).ok();
    }
}
