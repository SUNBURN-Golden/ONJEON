"""Rust emitter: vocabulary enums and wire structs (serde)."""
from __future__ import annotations

from schema_model import Model, Type, pascal

KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if",
    "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self",
    "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield", "try",
}

HEADER = """// @generated by packages/schemas/codegen/gen.py from packages/schemas/vocabulary.json and
// packages/schemas/json/*.schema.json. Do not edit; run `bash packages/schemas/codegen/gen.sh`.
"""


def doc(text: str, indent: str = "") -> str:
    out = []
    for line in text.strip().splitlines():
        line = line.rstrip()
        out.append(f"{indent}///{(' ' + line) if line else ''}")
    return "\n".join(out) + ("\n" if out else "")


def rust_type(t: Type) -> str:
    if t.kind == "string":
        base = "String"
    elif t.kind == "integer":
        base = "i64"
    elif t.kind == "number":
        base = "f64"
    elif t.kind == "boolean":
        base = "bool"
    elif t.kind == "any":
        return "serde_json::Value"
    elif t.kind == "array":
        base = f"Vec<{rust_type(t.item)}>"
    elif t.kind == "map":
        base = f"std::collections::BTreeMap<String, {rust_type(t.item)}>"
    elif t.kind == "ref":
        base = t.name
    elif t.kind == "enum":
        base = pascal(t.name)
    else:
        raise AssertionError(t.kind)
    return f"Option<{base}>" if t.nullable else base


def variant(code: str) -> str:
    v = pascal(code)
    if not v or v[0].isdigit():
        raise ValueError(f"cannot make a Rust variant from {code!r}")
    return v


def field_ident(name: str) -> tuple[str, bool]:
    return (name + "_", True) if name in KEYWORDS else (name, False)


def emit_vocabulary(model: Model) -> str:
    out = [HEADER, "use serde::{Deserialize, Serialize};\n",
           f'/// Version of packages/schemas/vocabulary.json these enums were generated from.\npub const VOCABULARY_VERSION: &str = "{model.vocabulary_version}";\n']
    for axis in model.axes.values():
        name = pascal(axis.id)
        variants = [variant(v["code"]) for v in axis.values]
        if len(set(variants)) != len(variants):
            raise ValueError(f"{axis.id}: variant name collision")
        out.append(doc(f"{axis.name_ko}: {axis.concept_ko}\n\nAxis `{axis.id}`. Unknown values fail to deserialize (never a default)."))
        out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]\n")
        out.append(f"pub enum {name} {{\n")
        for v in axis.values:
            out.append(doc(v["concept_ko"], "    "))
            out.append(f'    #[serde(rename = "{v["code"]}")]\n    {variant(v["code"])},\n')
        out.append("}\n\n")
        out.append(f"impl {name} {{\n")
        out.append(f'    pub const AXIS: &\'static str = "{axis.id}";\n')
        out.append(f"    pub const ALL: &'static [{name}] = &[\n")
        for v in axis.values:
            out.append(f"        {name}::{variant(v['code'])},\n")
        out.append("    ];\n\n")
        out.append("    pub fn as_str(self) -> &'static str {\n        match self {\n")
        for v in axis.values:
            out.append(f'            {name}::{variant(v["code"])} => "{v["code"]}",\n')
        out.append("        }\n    }\n}\n\n")
    out.append("/// Every axis with its codes, in vocabulary order. Used by tests to compare with vocabulary.json.\n")
    out.append("pub fn axes() -> Vec<(&'static str, Vec<&'static str>)> {\n    vec![\n")
    for axis in model.axes.values():
        name = pascal(axis.id)
        out.append(f"        ({name}::AXIS, {name}::ALL.iter().map(|v| v.as_str()).collect()),\n")
    out.append("    ]\n}\n")
    return "".join(out).rstrip() + "\n"


def emit_types(model: Model, structs=None, preamble: str | None = None, header: str = HEADER, cfg: dict | None = None) -> str:
    """`structs`/`preamble`/`header`/`cfg` let emit_api reuse this for the API crate (cfg: struct name -> attribute line)."""
    if preamble is None:
        preamble = "use super::vocabulary::*;\nuse serde::{Deserialize, Serialize};\n\n"
    out = [header, preamble]
    for st in (model.structs.values() if structs is None else structs):
        out.append(doc(st.description or st.name))
        if cfg and st.name in cfg:
            out.append(cfg[st.name] + "\n")
        out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n")
        out.append(f"pub struct {st.name} {{\n")
        for f in st.fields:
            ident, renamed = field_ident(f.name)
            if f.description:
                out.append(doc(f.description, "    "))
            attrs = []
            if renamed:
                attrs.append(f'rename = "{f.name}"')
            optional = not f.required
            ty = rust_type(f.type)
            if optional and not ty.startswith("Option<") and f.type.kind != "any":
                ty = f"Option<{ty}>"
            if optional:
                attrs.append("default")
                attrs.append('skip_serializing_if = "Option::is_none"')
            elif f.type.nullable and f.type.kind != "any":
                # required but nullable: the key must be present (null is fine). serde's derive
                # would otherwise treat a missing Option key as None.
                attrs.append('deserialize_with = "Option::deserialize"')
            if f.type.kind == "any" and optional:
                ty = "Option<serde_json::Value>"
            if attrs:
                out.append(f"    #[serde({', '.join(attrs)})]\n")
            out.append(f"    pub {ident}: {ty},\n")
        out.append("}\n\n")
    return "".join(out).rstrip() + "\n"


def emit_mod() -> str:
    return HEADER + "#![allow(clippy::all)]\n\npub mod types;\npub mod vocabulary;\n"


def emit(model: Model) -> dict:
    return {
        "mod.rs": emit_mod(),
        "vocabulary.rs": emit_vocabulary(model),
        "types.rs": emit_types(model),
    }
